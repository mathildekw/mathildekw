import { test, expect } from "@playwright/test";
test("join hub and referral funnel are responsive", async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem("mk_analytics_consent", "denied"));
  await page.route("**/buyer-funnel/public/events", (route) => route.fulfill({ status: 201, contentType: "application/json", body: '{"recorded":true}' }));
  await page.route("**/buyer-funnel/public/join", async (route) => {
    const payload = route.request().postDataJSON();
    expect(payload.lead_type).toBe("seller_referral");
    expect(payload.third_party_consent).toBe(true);
    expect(payload.privacy_consent).toBe(true);
    await route.fulfill({ status: 201, contentType: "application/json", body: '{"lead_id":"synthetic-test","possible_duplicate":false}' });
  });
  await page.goto("/nous-rejoindre/");
  await expect(page.locator("h1")).toContainText("travaillait ensemble");
  const menuButton = page.getByRole("button", { name: "Ouvrir le menu" });
  if (await menuButton.isVisible()) await menuButton.click();
  await expect(page.getByRole("link", { name: "Nous rejoindre" })).toBeVisible();
  await page.goto("/nous-rejoindre/apporteur-affaires/");
  await expect(page.locator("h1")).toContainText("Ton réseau peut te rapporter");
  await expect(page.locator("[data-gain-output]")).toHaveText(/337[\s\u202f]500 F CFP/);
  await page.locator("[data-referral-calculator]").evaluate((node) => { node.value = "4000000"; node.dispatchEvent(new Event("input", { bubbles: true })); });
  await expect(page.locator("[data-gain-output]")).toHaveText(/450[\s\u202f]000 F CFP/);
  await page.getByRole("link", { name: "Faire une recommandation" }).click();
  await expect(page.locator("#formulaire")).toBeInViewport();
  await page.locator('[name="property_type"][value="Maison"]').check();
  await page.getByRole("button", { name: "Continuer" }).click();
  await page.locator("#island").selectOption("Tahiti");
  await page.locator("#city").fill("Punaauia");
  await page.getByRole("button", { name: "Continuer" }).click();
  await expect(page.locator('[name="seller_project_stage"]')).toHaveCount(6);
  await page.locator('[name="seller_project_stage"][value="considering"]').check();
  await page.getByRole("button", { name: "Continuer" }).click();
  await page.locator("#owner_first_name").fill("Propriétaire fictif");
  await page.locator("#owner_phone").fill("+689 87 00 00 00");
  await page.getByRole("button", { name: "Continuer" }).click();
  await page.locator("#notes").fill("Données entièrement synthétiques pour le test.");
  await page.getByRole("button", { name: "Continuer" }).click();
  await page.locator("#referrer_first_name").fill("Apporteur");
  await page.locator("#referrer_last_name").fill("Test");
  await page.locator("#referrer_phone").fill("+689 88 00 00 00");
  await page.locator('[name="third_party_consent"]').check();
  await page.locator('[name="privacy_consent"]').check();
  await page.getByRole("button", { name: "Envoyer la recommandation" }).click();
  await expect(page.getByRole("heading", { name: "Merci pour la mise en relation" })).toBeVisible();
  await expect(page.locator("[data-whatsapp]")).toHaveAttribute("href", /wa\.me/);
  expect(await page.evaluate(() => document.documentElement.scrollWidth > document.documentElement.clientWidth + 1)).toBe(false);
});
